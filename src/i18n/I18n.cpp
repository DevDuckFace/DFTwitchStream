I18n& I18n::get() {
    static I18n instance;
    return instance;
}

void I18n::setLanguage(Language lang) { m_lang = lang; }

const char* I18n::tr(const char* key) const {
    if (m_lang == Language::Portuguese) {
        if (auto it = m_pt.find(key); it != m_pt.end()) return it->second.c_str();
    }
    if (auto it = m_en.find(key); it != m_en.end()) return it->second.c_str();
    return key;
}

std::string I18n::fmt(const char* key, const std::string& a) const {
    std::string s = tr(key);
    if (size_t p = s.find("{}"); p != std::string::npos) s.replace(p, 2, a);
    return s;
}

std::string I18n::fmt(const char* key, const std::string& a, const std::string& b) const {
    std::string s = fmt(key, a);
    if (size_t p = s.find("{}"); p != std::string::npos) s.replace(p, 2, b);
    return s;
}

